//! Build-time discovery of project templates.
//!
//! Every subdirectory of `templates/` that contains files is embedded into the
//! `ag` binary as a list of `(output path, content)` pairs. A file whose name
//! ends in `.tmpl` is written without that suffix; `{{name}}` is substituted at
//! scaffolding time. `template.toml` is metadata and is never scaffolded.
//!
//! New template directories are picked up on the next build automatically, so
//! adding a template never requires a change to the CLI source code.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let templates = manifest.join("../../templates");
    println!("cargo:rerun-if-changed={}", templates.display());

    let mut entries: Vec<(String, Vec<(String, String)>)> = Vec::new();
    if let Ok(read) = fs::read_dir(&templates) {
        for dir in read.flatten() {
            let path = dir.path();
            if !path.is_dir() {
                continue;
            }
            let Some(name) = dir.file_name().to_str().map(str::to_owned) else {
                continue;
            };
            let mut files = Vec::new();
            collect_files(&path, Path::new(""), &mut files);
            files.sort_by(|a, b| a.0.cmp(&b.0));
            if !files.is_empty() {
                entries.push((name, files));
            }
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let generated = out.join("templates_generated.rs");
    fs::write(&generated, render(&entries)).expect("write generated templates");
}

fn collect_files(root: &Path, relative: &Path, out: &mut Vec<(String, String)>) {
    let Ok(read) = fs::read_dir(root.join(relative)) else {
        return;
    };
    for item in read.flatten() {
        let name = item.file_name();
        let name = name.to_string_lossy();
        if name == "template.toml" {
            continue;
        }
        let child = relative.join(name.as_ref());
        let path = item.path();
        if path.is_dir() {
            collect_files(root, &child, out);
        } else if path.is_file() {
            let mut output = child.to_string_lossy().replace('\\', "/");
            if let Some(stripped) = output.strip_suffix(".tmpl") {
                output = stripped.to_owned();
            }
            if let Ok(content) = fs::read_to_string(&path) {
                out.push((output, content));
            }
        }
    }
}

fn render(entries: &[(String, Vec<(String, String)>)]) -> String {
    let mut code = String::from(
        "// Generated by crates/ag-cli/build.rs. Do not edit.\n\
         // Maps a template name to (output path, file content) pairs.\n",
    );
    code.push_str("pub(crate) static GENERATED_TEMPLATES: &[(&str, &[(&str, &str)])] = &[\n");
    for (name, files) in entries {
        code.push_str(&format!("    ({name:?}, &[\n"));
        for (path, content) in files {
            code.push_str(&format!("        ({path:?}, {content:?}),\n"));
        }
        code.push_str("    ]),\n");
    }
    code.push_str("];\n");

    code.push_str("#[allow(dead_code)] // Consumed by the optional TUI selectors.\n");
    code.push_str("pub(crate) static GENERATED_FILE_LISTS: &[(&str, &[&str])] = &[\n");
    for (name, files) in entries {
        code.push_str(&format!("    ({name:?}, &[\n"));
        for (path, _) in files {
            code.push_str(&format!("        {path:?},\n"));
        }
        code.push_str("    ]),\n");
    }
    code.push_str("];\n");
    code
}
