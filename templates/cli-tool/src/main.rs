//! Standalone CLI scaffold using clap and the shared `ag_core::AgError` type.
//!
//! Replace the example subcommands with your own logic. The binary keeps a
//! small, explicit surface: one parser, one match, typed errors.

use ag_core::AgError;
use clap::{Parser, Subcommand};

#[derive(Debug, Parser)]
#[command(name = "{{name}}", version, about = "Anti-Gravital CLI scaffold")]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Debug, Subcommand)]
enum Commands {
    /// Write a starter configuration file.
    Init {
        /// Destination path.
        #[arg(long, default_value = "config.toml")]
        output: String,
    },
    /// Report the size of a configuration file.
    Inspect {
        /// Path to read.
        path: String,
    },
    /// List the available subcommands.
    Commands,
}

fn main() -> Result<(), AgError> {
    let cli = Cli::parse();

    match cli.command {
        Commands::Init { output } => {
            if output.trim().is_empty() {
                return Err(AgError::Validation("output path must not be empty".into()));
            }
            std::fs::write(&output, format!("# generated by {}\n", env!("CARGO_PKG_NAME")))
                .map_err(AgError::Io)?;
            println!("wrote {output}");
        }
        Commands::Inspect { path } => {
            let content = std::fs::read_to_string(&path).map_err(AgError::Io)?;
            println!("{path}: {} bytes", content.len());
        }
        Commands::Commands => {
            println!("init, inspect, commands");
        }
    }

    Ok(())
}
